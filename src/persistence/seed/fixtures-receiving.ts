function createSeedWoodRecord(
  raw: Omit<
    WoodReceivingRecord,
    | 'volumeDiscrepancyM3'
    | 'pieceDiscrepancy'
    | 'timberGrossTotal'
    | 'timberPphAmount'
    | 'timberNetPayable'
    | 'freightGrossTotal'
    | 'freightPphAmount'
    | 'freightNetPayable'
    | 'grandNetPayable'
  > & {
    freightPphRate?: number;
    freightPphAmount?: number;
    timberGrossTotal?: number | null;
    timberPphAmount?: number | null;
    timberNetPayable?: number | null;
    freightGrossTotal?: number;
    freightNetPayable?: number;
    grandNetPayable?: number | null;
    volumeDiscrepancyM3?: number;
    pieceDiscrepancy?: number;
  }
): WoodReceivingRecord {
  const freightPphRate = raw.freightPphRate ?? 2.0;
  const freightGross = Number((raw.tallyVolumeM3 * raw.freightRatePerM3).toFixed(2));
  const freightPphAmount = raw.freightPphAmount ?? Number((freightGross * (freightPphRate / 100)).toFixed(2));
  const calc = computeRecordCalculations({
    ...raw,
    freightPphAmount,
  });
  return {
    ...raw,
    ...calc,
    freightPphAmount,
  };
}

